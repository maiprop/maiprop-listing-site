#!/usr/bin/env node

import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const repoRoot = process.cwd();
const distDir = resolve(repoRoot, "dist");
const curatedRoutesPath = resolve(repoRoot, "public", "_routes.json");
const outDir = resolve(repoRoot, ".tmp", "cloudflare-pages-functions");
const generatedWorkerPath = resolve(outDir, "index.js");
const generatedWorkerFallbackPath = resolve(outDir, "_worker.js");
const generatedRoutesPath = resolve(outDir, "_routes.json");
const distWorkerPath = resolve(distDir, "_worker.js");
const distRoutesPath = resolve(distDir, "_routes.json");

const requiredFunctionPaths = [
  "/api/public/listings",
  "/api/public/listing",
  "/api/public/homepage",
  "/api/public/open-houses",
  "/api/public/auctions",
  "/api/public/similar-listings",
  "/sitemap-dynamic.xml",
  "/__unlock",
  "/listings",
  "/auctions",
  "/property/00000000-0000-0000-0000-000000000000",
];

const requiredStaticExcludes = [
  "/assets/*",
  "/docs/*",
  "/images/*",
  "/lovable-uploads/*",
  "/favicon.ico",
  "/robots.txt",
  "/sitemap.xml",
];

if (!existsSync(distDir)) {
  console.error("dist/ does not exist. Run npm run build before packaging Pages Functions.");
  process.exit(1);
}

function readJson(path, label) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    console.error(`Could not read ${label} at ${relative(repoRoot, path)}: ${error.message}`);
    process.exit(1);
  }
}

function uniq(values) {
  return [...new Set(values.filter((value) => typeof value === "string" && value.trim().length > 0))];
}

function patternMatches(pattern, path) {
  if (pattern === "/*") return path.startsWith("/");
  if (pattern.endsWith("/*")) return path.startsWith(pattern.slice(0, -1));
  return pattern === path;
}

function routeIncluded(routes, path) {
  return routes.include.some((pattern) => patternMatches(pattern, path));
}

function routeExcluded(routes, path) {
  return routes.exclude.some((pattern) => patternMatches(pattern, path));
}

function mergeRoutes(generatedRoutes) {
  if (!existsSync(curatedRoutesPath)) return generatedRoutes;
  const curatedRoutes = readJson(curatedRoutesPath, "curated Cloudflare Pages routes");
  return {
    ...generatedRoutes,
    version: generatedRoutes.version ?? curatedRoutes.version ?? 1,
    description: "Generated by build-cloudflare-pages-worker.mjs with repository route exclusions",
    include: uniq([...(generatedRoutes.include ?? []), ...(curatedRoutes.include ?? [])]),
    exclude: uniq([...(curatedRoutes.exclude ?? [])]),
  };
}

function validateRoutes(routes) {
  if (!Array.isArray(routes.include) || routes.include.length === 0) {
    console.error("Generated _routes.json must include at least one function invocation route.");
    process.exit(1);
  }
  if (!Array.isArray(routes.exclude)) {
    console.error("Generated _routes.json must contain an exclude array.");
    process.exit(1);
  }

  for (const path of requiredFunctionPaths) {
    if (!routeIncluded(routes, path) || routeExcluded(routes, path)) {
      console.error(`Generated _routes.json would not invoke the Pages Function for ${path}.`);
      process.exit(1);
    }
  }

  for (const pattern of requiredStaticExcludes) {
    if (!routes.exclude.includes(pattern)) {
      console.error(`Generated _routes.json must exclude static route ${pattern} to avoid unnecessary Pages Function invocations.`);
      process.exit(1);
    }
  }
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const wranglerArgs = [
  "pages",
  "functions",
  "build",
  "functions",
  "--outdir",
  relative(repoRoot, outDir),
  "--output-routes-path",
  relative(repoRoot, generatedRoutesPath),
  "--compatibility-date",
  "2026-05-19",
];

const windowsQuote = (value) => {
  if (!/[ \t"&|<>^]/.test(value)) return value;
  return `"${value.replace(/"/g, '\\"')}"`;
};

const npxArgs = ["--yes", "wrangler", ...wranglerArgs];
const result =
  process.platform === "win32"
    ? spawnSync("cmd.exe", ["/d", "/s", "/c", `npx ${npxArgs.map(windowsQuote).join(" ")}`], {
        cwd: repoRoot,
        env: process.env,
        stdio: "inherit",
      })
    : spawnSync("npx", npxArgs, {
        cwd: repoRoot,
        env: process.env,
        stdio: "inherit",
      });

if (result.error) {
  console.error(`Failed to run Wrangler Pages Functions build: ${result.error.message}`);
  process.exit(1);
}

if (result.status !== 0) {
  process.exit(result.status ?? 1);
}

const actualGeneratedWorkerPath = existsSync(generatedWorkerPath) ? generatedWorkerPath : generatedWorkerFallbackPath;
if (!existsSync(actualGeneratedWorkerPath)) {
  console.error(
    `Wrangler did not generate ${relative(repoRoot, generatedWorkerPath)} or ${relative(repoRoot, generatedWorkerFallbackPath)}.`,
  );
  process.exit(1);
}
if (!existsSync(generatedRoutesPath)) {
  writeFileSync(
    generatedRoutesPath,
    JSON.stringify({
      version: 1,
      description: "Generated fallback by scripts/build-cloudflare-pages-worker.mjs",
      include: ["/*"],
      exclude: [],
    }, null, 2),
  );
}

const worker = readFileSync(actualGeneratedWorkerPath, "utf8");
if (!worker.includes('routePath: "/api/public/listings"')) {
  console.error("Generated Pages worker is missing the /api/public/listings route.");
  process.exit(1);
}
if (!worker.includes("env.ASSETS.fetch")) {
  console.error("Generated Pages worker is missing the ASSETS fallback.");
  process.exit(1);
}

const routes = mergeRoutes(readJson(generatedRoutesPath, "generated Cloudflare Pages routes"));
validateRoutes(routes);
writeFileSync(generatedRoutesPath, `${JSON.stringify(routes, null, 2)}\n`);

copyFileSync(actualGeneratedWorkerPath, distWorkerPath);
copyFileSync(generatedRoutesPath, distRoutesPath);

console.log(`Packaged Cloudflare Pages worker: ${relative(repoRoot, distWorkerPath)}`);
console.log(`Packaged Cloudflare Pages routes: ${relative(repoRoot, distRoutesPath)}`);
